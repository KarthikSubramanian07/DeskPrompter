#!/usr/bin/env python3
"""Generate src/fold_table.rs: NFKD + accent stripping for the ranges the
aligner cares about, so the wasm doesn't ship full Unicode normalization
tables (~100 KB). `cargo test` checks the table against unicode-normalization.

    python3 crates/aligner/tools/gen_fold.py > crates/aligner/src/fold_table.rs
"""
import unicodedata

RANGES = [
    (0x00A0, 0x024F),  # Latin-1 Supplement, Latin Extended-A/B
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x1E00, 0x1EFF),  # Latin Extended Additional (Vietnamese)
    (0x1F00, 0x1FFF),  # Greek Extended
    (0x2070, 0x209F),  # super/subscripts
    (0x2150, 0x218F),  # number forms
    (0xF900, 0xFAFF),  # CJK compatibility ideographs
    (0xFB00, 0xFB06),  # Latin ligatures
    (0xFF01, 0xFFEE),  # full-width / half-width forms
]


def fold(c):
    out = []
    base = 0
    for d in unicodedata.normalize("NFKD", c):
        if unicodedata.combining(d) or unicodedata.category(d) in ("Mn", "Me"):
            if base < 0x530:
                continue
        else:
            base = ord(d)
        out.append(d)
    return "".join(out)


single, multi = [], []
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        c = chr(cp)
        if unicodedata.category(c) == "Cn":
            continue
        f = fold(c)
        if f == c:
            continue
        if len(f) == 1 and ord(f) <= 0xFFFF:
            single.append((cp, ord(f)))
        else:
            multi.append((cp, f))

print("// @generated by tools/gen_fold.py (Unicode %s). Do not edit." % unicodedata.unidata_version)
print("// NFKD with accents removed from Latin/Greek/Cyrillic letters, per code point.")
print("")
print("/// (from, to) pairs, sorted by `from`.")
print("pub static SINGLE: [(u16, u16); %d] = [" % len(single))
for i in range(0, len(single), 6):
    print("    " + " ".join("(0x%04X, 0x%04X)," % p for p in single[i:i + 6]))
print("];")
print("")
print("/// Code points that fold to several characters, sorted.")
print("pub static MULTI: [(u16, &str); %d] = [" % len(multi))
for cp, f in multi:
    esc = "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else "\\u{%X}" % ord(ch) for ch in f)
    print('    (0x%04X, "%s"),' % (cp, esc))
print("];")
